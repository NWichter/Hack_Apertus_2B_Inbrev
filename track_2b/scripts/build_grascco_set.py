#!/usr/bin/env python3
"""Build an extra report_received test set from GraSCCo.

GraSCCo (Graz Synthetic Clinical text Corpus, Modersohn et al. 2022) holds 63
synthetic German clinical letters to a GP. This script wraps up to 40 of them,
verbatim (optionally shortened), into Inbrev inbox messages with fixed labels.
No text is generated by a model; every choice is deterministic (seed 2026).

python scripts/build_grascco_set.py --download   # fetch Zenodo record into data/external/grascco/
python scripts/build_grascco_set.py              # build data/grascco/messages.jsonl
python scripts/validate.py --grid data/external/grascco/grid.jsonl \
    --report data/external/grascco/validation-report.md data/grascco/messages.jsonl
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import re
import sys
import unicodedata
import urllib.request
from datetime import date, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "external" / "grascco"
OUT_PATH = ROOT / "data" / "grascco" / "messages.jsonl"
GRID_PATH = RAW_DIR / "grid.jsonl"

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate import EMAIL_RE, PHONE_RE, URL_RE, shingles  # noqa: E402

SEED = 2026
MAX_DOCS = 40
MIN_CHARS = 400
MAX_CHARS = 6000
NEAR_DUP = 0.5

ZENODO_RECORD = "18874981"
ZENODO_API = f"https://zenodo.org/api/records/{ZENODO_RECORD}"
SOURCE_INFO = {
    "source": "GraSCCo",
    "dataset": "GraSCCo - Graz Synthetic Clinical text Corpus, version 1.1",
    "license": "CC-BY-4.0",
    "license_url": "https://creativecommons.org/licenses/by/4.0/",
    "license_note": "Zenodo licence field: cc-by-4.0; the record description also states a CC0 dedication. This set follows the stricter CC BY 4.0 (attribution, changes indicated).",
    "url": f"https://zenodo.org/records/{ZENODO_RECORD}",
    "doi": "10.5281/zenodo.18874981",
    "concept_doi": "10.5281/zenodo.6539130",
    "citation": "Modersohn L, Schulz S, Lohr C, Hahn U. GraSCCo - The First Publicly Shareable, Multiply-Alienated German Clinical Text Corpus. Studies in Health Technology and Informatics (GMDS 2022). 2022. doi:10.3233/SHTI220805. Data: Schulz S. GraSCCo (1.1). Zenodo. 2026. doi:10.5281/zenodo.18874981",
}

INSTITUTIONS = [
    ("Spital Beispielthal", "spital-beispielthal"),
    ("Regionalspital Musterwil", "regionalspital-musterwil"),
    ("Klinik Seeblick Beispielstadt", "klinik-seeblick"),
    ("Spitalzentrum Talheim-Beispiel", "spitalzentrum-talheim"),
    ("Privatklinik Am Musterhang", "klinik-musterhang"),
    ("Universitäres Beispielspital Nordtal", "beispielspital-nordtal"),
]

REPORT_TYPES = {
    "discharge": "Austrittsbericht",
    "outpatient": "Facharztbericht",
    "imaging": "Bildgebungsbefund",
    "findings": "Befundbericht",
}

SUBJECTS = [
    ("S1", "{rt}"),
    ("S2", "{rt} zur Kenntnisnahme"),
    ("S3", "Bericht zu Ihrem Patienten: {rt}"),
    ("S4", "Zustellung {rt}"),
]

WRAPPERS = {
    "hin_mail": [
        (
            "W1-hin",
            "Guten Tag\n\nIm Auftrag von {inst} übermitteln wir Ihnen den {rt} zu Ihrem "
            "Patienten bzw. Ihrer Patientin.\n\nFreundliche Grüsse\nSekretariat\n\n",
        ),
        (
            "W2-hin",
            "Sehr geehrte Frau Kollegin, sehr geehrter Herr Kollege\n\nAnbei der {rt} "
            "von {inst} zur Weiterbehandlung.\n\nMit kollegialen Grüssen\nSekretariat\n\n",
        ),
    ],
    "fax": [
        (
            "W3-fax",
            "FAX-MITTEILUNG\nAbsender: {inst}\nSeiten: {pages}\n\nBetrifft: {rt}\n\n",
        ),
    ],
    "email": [
        (
            "W4-email",
            "Sehr geehrte Damen und Herren\n\nNachstehend erhalten Sie den {rt} von {inst}. "
            "Bei Fragen stehen wir gerne zur Verfügung.\n\nFreundliche Grüsse\nSekretariat\n\n",
        ),
        (
            "W5-email",
            "Guten Tag\n\nWir senden Ihnen den {rt} von {inst} für Ihre Unterlagen.\n\n"
            "Freundliche Grüsse\nSekretariat\n\n",
        ),
    ],
}
CHANNELS = ["hin_mail", "fax", "email"]
DISCHARGE_RE = (
    r"Entlassungs|\b[Ss]tationär|stat\. Behandlung|Station\b|Aufenthalt|aufhielt"
    r"|Anschlu(?:ß|ss)heilbehandlung|behandelten .{0,40}vom"
)


def download(dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(ZENODO_API, timeout=60) as r:
        record = json.load(r)
    if (record["metadata"].get("license") or {}).get("id") != "cc-by-4.0":
        raise SystemExit(f"unexpected licence: {record['metadata'].get('license')}")
    for f in record["files"]:
        target = dest / unicodedata.normalize("NFC", f["key"])
        if (
            target.exists()
            and "md5:" + hashlib.md5(target.read_bytes()).hexdigest() == f["checksum"]
        ):
            continue
        with urllib.request.urlopen(f["links"]["self"], timeout=60) as r:
            data = r.read()
        if "md5:" + hashlib.md5(data).hexdigest() != f["checksum"]:
            raise SystemExit(f"checksum mismatch: {f['key']}")
        target.write_bytes(data)
    print(f"{len(record['files'])} files in {dest}")


def load_docs(raw_dir: Path) -> dict[str, tuple[str, str]]:
    docs = {}
    for p in sorted(raw_dir.glob("*.txt")):
        raw = p.read_bytes()
        text = raw.decode("utf-8").lstrip("\ufeff").strip()
        name = unicodedata.normalize("NFC", p.name)
        docs[name] = (text, hashlib.md5(raw).hexdigest())
    return dict(sorted(docs.items()))


def exclusion_reason(text: str) -> str | None:
    if len(text) < MIN_CHARS:
        return f"shorter than {MIN_CHARS} characters"
    if EMAIL_RE.search(text) or URL_RE.search(text):
        return "contains an e-mail address or URL (possibly real)"
    if any(m.group(1) != "000" for m in PHONE_RE.finditer(text)):
        return "contains a phone number in Swiss format outside the 000 block"
    return None


def report_kind(text: str) -> str:
    if re.search(r"Röntgenabteilung|Radiologie|CT Abdomen", text[:400]):
        return "imaging"
    if re.search(DISCHARGE_RE, text):
        return "discharge"
    if re.search(
        r"Ambulan|ambulant|AMBULANZ|Kontrolluntersuchung|Vorstellung", text[:400]
    ):
        return "outpatient"
    return "findings"


def shorten(text: str) -> str:
    if len(text) <= MAX_CHARS:
        return text
    cut = text[:MAX_CHARS]
    for sep in ("\n\n", "\n", ". "):
        i = cut.rfind(sep)
        if i > MAX_CHARS * 0.7:
            return cut[: i + (1 if sep == ". " else 0)].rstrip()
    return cut.rstrip()


def workdays_october_2026() -> list[date]:
    d = date(2026, 10, 1)
    days = []
    while d.month == 10:
        if d.weekday() < 5:
            days.append(d)
        d += timedelta(days=1)
    return days


def select(docs: dict[str, tuple[str, str]]) -> tuple[list[str], dict[str, str]]:
    excluded = {}
    kept = []
    sh = {}
    for name, (text, _) in docs.items():
        reason = exclusion_reason(text)
        if reason:
            excluded[name] = reason
            continue
        s = shingles(text)
        dup = next(
            (k for k in kept if len(s & sh[k]) / len(s | sh[k]) >= NEAR_DUP), None
        )
        if dup:
            excluded[name] = f"near-duplicate of {dup}"
            continue
        kept.append(name)
        sh[name] = s
    rng = random.Random(SEED)
    chosen = sorted(rng.sample(kept, min(MAX_DOCS, len(kept))))
    rng.shuffle(chosen)
    return chosen, excluded


def build(raw_dir: Path) -> tuple[list[dict], dict[str, str]]:
    docs = load_docs(raw_dir)
    if not docs:
        raise SystemExit(f"no .txt files in {raw_dir}; run with --download")
    chosen, excluded = select(docs)
    rng = random.Random(SEED + 1)
    days = workdays_october_2026()
    rows = []
    for i, name in enumerate(chosen):
        original, md5 = docs[name]
        text = shorten(original)
        kind = report_kind(original)
        rt = REPORT_TYPES[kind]
        inst, slug = INSTITUTIONS[rng.randrange(len(INSTITUTIONS))]
        subject_id, subject_tpl = SUBJECTS[rng.randrange(len(SUBJECTS))]
        subject = subject_tpl.format(rt=rt)
        channel = CHANNELS[i % len(CHANNELS)]
        variants = WRAPPERS[channel]
        wrapper_id, wrapper_tpl = variants[(i // len(CHANNELS)) % len(variants)]
        cover = wrapper_tpl.format(inst=inst, rt=rt, pages=len(text) // 2500 + 2)
        body = cover + text
        recv = datetime.combine(days[rng.randrange(len(days))], datetime.min.time())
        recv += timedelta(hours=rng.randint(7, 17), minutes=rng.randrange(60))
        if channel == "fax":
            sender = f"{inst}, Fax 044 000 {rng.randint(10, 99)} {rng.randint(10, 99)}"
        elif channel == "hin_mail":
            sender = f"Sekretariat {inst} <sekretariat@{slug}.hin.example>"
        else:
            sender = f"Sekretariat {inst} <berichte@{slug}.example>"
        mid = f"grascco-{i + 1:03d}"
        label = {
            "route": "report_received",
            "deadline": "today",
            "deadline_date": None,
            "assignee": "doctor",
            "safety_flag": False,
            "abstain": False,
            "patient": {},
            "fields": {"report_type": rt, "sender_institution": inst},
            "evidence": [
                {"field": "route", "quote": subject},
                {"field": "fields.report_type", "quote": rt},
                {"field": "fields.sender_institution", "quote": inst},
            ],
        }
        rows.append(
            {
                "message_id": mid,
                "language": "de",
                "channel": channel,
                "sender_type": "hospital",
                "sender": sender,
                "received_at": recv.strftime("%Y-%m-%dT%H:%M"),
                "subject": subject,
                "body": body,
                "source": "grascco",
                "label": label,
                "provenance": {
                    **SOURCE_INFO,
                    "original_file": name,
                    "original_md5": md5,
                    "original_chars": len(original),
                    "kept_chars": len(text),
                    "truncated": len(text) < len(original),
                    "report_kind": kind,
                    "wrapper_template": wrapper_id,
                    "subject_template": subject_id,
                    "changes": "BOM and surrounding whitespace removed; "
                    + (
                        f"shortened to the first {len(text)} of {len(original)} characters at a line or sentence break; "
                        if len(text) < len(original)
                        else ""
                    )
                    + "fictitious cover text, subject, sender and received_at added by template",
                    "labels_by": "fixed rule in scripts/build_grascco_set.py, not reviewed by a person",
                    "human_review": False,
                },
            }
        )
    return rows, excluded


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--download", action="store_true", help="fetch the Zenodo record first"
    )
    ap.add_argument("--raw-dir", type=Path, default=RAW_DIR)
    ap.add_argument("--out", type=Path, default=OUT_PATH)
    ap.add_argument("--grid-out", type=Path, default=GRID_PATH)
    args = ap.parse_args()

    if args.download:
        download(args.raw_dir)
    rows, excluded = build(args.raw_dir)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    args.grid_out.parent.mkdir(parents=True, exist_ok=True)
    with args.grid_out.open("w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            spec = {
                k: r[k] for k in ("message_id", "language", "channel", "received_at")
            }
            spec["label"] = {
                k: r["label"][k]
                for k in (
                    "route",
                    "deadline",
                    "deadline_date",
                    "assignee",
                    "safety_flag",
                    "abstain",
                )
            }
            f.write(json.dumps(spec, ensure_ascii=False) + "\n")
    for name, reason in excluded.items():
        print(f"excluded {name}: {reason}")
    mean = sum(len(r["body"]) for r in rows) / max(1, len(rows))
    print(
        f"{len(rows)} messages -> {args.out} (mean body {mean:.0f} chars, "
        f"{sum(r['provenance']['truncated'] for r in rows)} shortened)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
